"""Data schemas for documents, chunks, and metadata in the RAG pipeline."""

from typing import Any, Literal

from pydantic import BaseModel, Field


class RawPage(BaseModel):
    """Represents an extracted page or section from a source document."""

    page_number: int = Field(
        ...,
        ge=1,
        description="1-based page number or section index in the original file.",
    )
    text: str = Field(..., description="Cleaned text content of the page.")


class DocumentMetadata(BaseModel):
    """Metadata describing a loaded source document."""

    document_id: str = Field(..., description="Unique document identifier (e.g., hash or slug).")
    source: str = Field(..., description="Filename or relative path of the source document.")
    file_type: Literal["pdf", "docx", "txt", "md"] = Field(..., description="File extension format.")
    life_stage: str = Field(
        ...,
        description="Target wellness journey (e.g., 'beauty_radiance', 'cycle_fertility', 'general').",
    )
    category: str = Field(
        default="general",
        description="Wellness domain category (e.g., 'nutrition', 'hormonal_patterns').",
    )
    title: str | None = Field(default=None, description="Human-readable title if available.")
    total_pages: int = Field(default=1, ge=1, description="Total number of extracted pages.")
    file_hash: str = Field(..., description="SHA-256 hash of file content for deduplication.")


class LoadedDocument(BaseModel):
    """In-memory representation of an ingested document before chunking."""

    metadata: DocumentMetadata
    pages: list[RawPage] = Field(default_factory=list)
    full_text: str = Field(..., description="Aggregated cleaned text of the document.")


class ChunkMetadata(BaseModel):
    """Metadata attached to each indexed vector chunk."""

    document_id: str = Field(..., description="Unique parent document identifier.")
    source: str = Field(..., description="Original filename (e.g., 'nutrition_guide.pdf').")
    life_stage: str = Field(
        ...,
        description="Primary life-stage journey ('beauty_radiance', 'cycle_fertility', etc.).",
    )
    category: str = Field(
        default="general",
        description="Specific wellness topic or category.",
    )
    content_type: str = Field(
        default="educational",
        description="Type of content (e.g. 'educational', 'guideline', 'clinical_reference').",
    )
    page_number: int | None = Field(
        default=None,
        description="1-based page number where the chunk content originated.",
    )
    chunk_index: int = Field(..., ge=0, description="0-based sequential index within the document.")
    total_chunks: int = Field(default=1, ge=1, description="Total number of chunks in parent document.")

    def to_chroma_metadata(self) -> dict[str, Any]:
        """Convert metadata to flat dictionary format required by ChromaDB.

        ChromaDB only supports str, int, float, bool as metadata values.
        """
        return {
            "document_id": self.document_id,
            "source": self.source,
            "life_stage": self.life_stage,
            "category": self.category,
            "content_type": self.content_type,
            "page_number": self.page_number if self.page_number is not None else -1,
            "chunk_index": self.chunk_index,
            "total_chunks": self.total_chunks,
        }

    @classmethod
    def from_chroma_metadata(cls, data: dict[str, Any]) -> "ChunkMetadata":
        """Reconstruct ChunkMetadata from ChromaDB flat dictionary."""
        page_num = data.get("page_number", -1)
        return cls(
            document_id=str(data.get("document_id", "")),
            source=str(data.get("source", "")),
            life_stage=str(data.get("life_stage", "general")),
            category=str(data.get("category", "general")),
            content_type=str(data.get("content_type", "educational")),
            page_number=page_num if page_num != -1 else None,
            chunk_index=int(data.get("chunk_index", 0)),
            total_chunks=int(data.get("total_chunks", 1)),
        )


class DocumentChunk(BaseModel):
    """An indexed text chunk with associated metadata and optional embedding."""

    chunk_id: str = Field(..., description="Unique chunk ID (e.g., 'doc_abc123_chunk_0').")
    text: str = Field(..., description="Chunk text content to be embedded and searched.")
    metadata: ChunkMetadata
    embedding: list[float] | None = Field(
        default=None,
        description="Dense vector embedding generated by the embedding model.",
    )


class RetrievedChunk(BaseModel):
    """A chunk retrieved from vector similarity search with distance and relevance scores."""

    chunk_id: str = Field(..., description="Chunk identifier.")
    text: str = Field(..., description="Retrieved chunk text content.")
    metadata: ChunkMetadata = Field(..., description="Originating document and page metadata.")
    distance: float = Field(..., description="Raw vector distance (cosine distance).")
    similarity_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Normalized similarity score (1.0 - distance in cosine space).",
    )


class CollectionStats(BaseModel):
    """Aggregated statistics for a vector store collection."""

    collection_name: str
    total_chunks: int
    total_documents: int
    available_life_stages: list[str]
    available_categories: list[str]
